
public class ElseIf2 {
    public static void main(String[] args) {
        int A = 1;
        int B = 4;
        int C = 8;

        
        if ((A >= B) && (B >= C)){
            System.out.println("A");
        }
        else if ((B >= C)){
            System.out.println("B");

        }
        else{
            System.out.println("C");
        }
            
        
        
    }
    
}
